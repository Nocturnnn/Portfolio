"""Regenerate responsive portfolio thumbnails: python tools/optimize-images.py.

Requires Pillow. Originals are retained; the site uses the generated manifest.
"""
from pathlib import Path
import json
import re
import unicodedata

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "img" / "portifolio"
OUTPUT = ROOT / "img" / "responsive"
WIDTHS = (480, 800, 1200)


def main():
    OUTPUT.mkdir(exist_ok=True)
    manifest = {}
    stems = set()
    total_source = total_small = 0
    for path in sorted(SOURCE.iterdir()):
        if path.suffix.lower() not in (".png", ".jpg", ".jpeg", ".webp"):
            continue
        stem = unicodedata.normalize("NFKD", path.stem).encode("ascii", "ignore").decode()
        stem = re.sub(r"[^a-z0-9]+", "-", stem.lower()).strip("-")
        if stem in stems:
            raise ValueError(f"Duplicate thumbnail name: {stem}")
        stems.add(stem)
        with Image.open(path) as original:
            image = ImageOps.exif_transpose(original).convert("RGB")
            width, height = image.size
            variants = []
            for size in sorted(set(min(w, width) for w in WIDTHS)):
                destination = OUTPUT / f"{stem}-{size}.webp"
                thumb = image.resize((size, round(height * size / width)), Image.Resampling.LANCZOS)
                thumb.save(destination, "WEBP", quality=80, method=6)
                variants.append((size, destination.relative_to(ROOT).as_posix()))
            default = min(variants, key=lambda item: abs(item[0] - 800))
            manifest[path.relative_to(ROOT).as_posix()] = {
                "src": default[1],
                "srcset": ", ".join(f"{name} {size}w" for size, name in variants),
                "width": width,
                "height": height,
            }
            total_source += path.stat().st_size
            total_small += (ROOT / variants[0][1]).stat().st_size
    (ROOT / "js" / "project-images.js").write_text(
        "// Generated by tools/optimize-images.py. Do not edit by hand.\n"
        + "window.portfolioImages = " + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    with Image.open(ROOT / "img" / "favicon" / "favicon.jpg") as source:
        source.convert("RGB").resize((64, 64), Image.Resampling.LANCZOS).save(
            ROOT / "img" / "favicon" / "favicon-64.png", optimize=True
        )
    print(f"{len(manifest)} projects; originals {total_source / 1e6:.2f} MB; 480px variants {total_small / 1e6:.2f} MB")
    print(f"Thumbnail reduction: {(1 - total_small / total_source) * 100:.1f}%")


if __name__ == "__main__":
    main()
